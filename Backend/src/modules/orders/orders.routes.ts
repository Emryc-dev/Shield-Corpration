import { Router } from "express";
import { z } from "zod";
import { authenticate } from "../../middleware/auth";
import { validate } from "../../middleware/validate";
import { asyncHandler } from "../../utils/async-handler";
import { ok } from "../../utils/response";
import { ordersService } from "./orders.service";
const shippingSchema = z.object({ body: z.object({ recipientName: z.string().min(2), recipientEmail: z.email(), recipientPhone: z.string().min(6), address: z.string().min(5), city: z.string().min(2), country: z.string().min(2), shippingMethod: z.string().min(2) }) });
export const ordersRouter = Router();
ordersRouter.use(authenticate);
ordersRouter.post("/", validate(shippingSchema), asyncHandler(async (req, res) => ok(res, await ordersService.create(req.user!.id, req.body), 201)));
ordersRouter.get("/", asyncHandler(async (req, res) => ok(res, await ordersService.list(req.user!.id, req.query))));
ordersRouter.get("/:id", asyncHandler(async (req, res) => ok(res, await ordersService.one(req.user!.id, String(req.params.id)))));
