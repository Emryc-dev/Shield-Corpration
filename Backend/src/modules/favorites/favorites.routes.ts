import { Router } from "express";
import { z } from "zod";
import { prisma } from "../../config/prisma";
import { authenticate } from "../../middleware/auth";
import { validate } from "../../middleware/validate";
import { asyncHandler } from "../../utils/async-handler";
import { ok } from "../../utils/response";
export const favoritesRouter = Router();
favoritesRouter.use(authenticate);
favoritesRouter.get("/", asyncHandler(async (req, res) => ok(res, await prisma.favorite.findMany({ where: { userId: req.user!.id }, include: { product: { include: { images: { orderBy: { position: "asc" } }, category: true } } }, orderBy: { createdAt: "desc" } }))));
favoritesRouter.post("/", validate(z.object({ body: z.object({ productId: z.string().min(1) }) })), asyncHandler(async (req, res) => ok(res, await prisma.favorite.upsert({ where: { userId_productId: { userId: req.user!.id, productId: req.body.productId } }, create: { userId: req.user!.id, productId: req.body.productId }, update: {} }), 201)));
favoritesRouter.delete("/:productId", asyncHandler(async (req, res) => { await prisma.favorite.deleteMany({ where: { userId: req.user!.id, productId: String(req.params.productId) } }); return ok(res, { removed: true }); }));
